package io.openems.edge.controller.ess.chargedischargelimiter.cluster;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Controller Ess Charge/Discharge Limiter Cluster", //
		description = "Reports the SoC window and the allowed power of an ESS cluster to the energy optimizer "
				+ "(Time-of-Use-Tariff): the sum over the Charge/Discharge Limiters of the cluster members. "
				+ "The limiters of the members keep controlling their ESS; this controller controls nothing. "
				+ "Switch 'Report to Energy-Scheduler' off at the limiters of the members, and place this controller "
				+ "before the Time-of-Use-Tariff controller in the scheduler.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "chargeDischargeLimiterCluster0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "EssCluster-ID", description = "ID of the ESS cluster (e.g. Ess.Cluster.Hybrid) whose "
			+ "members have Charge/Discharge Limiters. A member without a limiter counts with its whole capacity "
			+ "and the power its ESS allows.")
	String ess_id() default "essCluster";

	@AttributeDefinition(name = "Report to Energy-Scheduler", description = "Reports the summed SoC window (lower "
			+ "and upper end in Wh) and the power the members allow right now to the energy optimizer. Off: the "
			+ "channels are still filled, the optimizer gets nothing from this controller.")
	boolean reportToEnergyScheduler() default true;

	@AttributeDefinition(name = "Debug Mode", description = "Logs the summary of the members every cycle.")
	boolean debugMode() default false;

	@AttributeDefinition(name = "Ess target filter", description = "This is auto-generated by 'Ess-ID'.")
	String ess_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Controller Ess Charge/Discharge Limiter Cluster [{id}]";
}
