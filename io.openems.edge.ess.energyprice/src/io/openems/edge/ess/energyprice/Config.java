package io.openems.edge.ess.energyprice;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Ess Energy Price", //
		description = "Keeps the price of the energy stored in one ESS: a running inventory of the content with its "
				+ "volume-weighted average purchase price. Charged energy counts at the grid buy price for the share "
				+ "bought from the grid and at the feed-in tariff for the share from PV; discharging and the SoC "
				+ "calibration leave the price unchanged. 'Price' is the price of a delivered kWh, losses included.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "essEnergyPrice0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Ess-ID", description = "ID of the ESS. A hybrid ESS (DC-coupled PV) counts with its "
			+ "DC battery power and DC energy counters, an AC ESS with its AC values.")
	String ess_id() default "ess0";

	@AttributeDefinition(name = "Grid buy price channel", description = "Channel with the grid buy price of the "
			+ "current quarter-hour [Currency/MWh], e.g. the Time-of-Use-Tariff controller. While the channel has no "
			+ "value the last known price is used; without any price the charged energy counts without price.")
	String priceChannel() default "ctrlToU1/QuarterlyPrices";

	@AttributeDefinition(name = "Feed-in tariff [Cent/kWh]", description = "Value of PV energy charged into the ESS.")
	double feedInTariff() default 7;

	@AttributeDefinition(name = "Efficiency period [days]", description = "The round-trip efficiency is measured from "
			+ "the charge and discharge energy of the ESS over this period (SoC-corrected) and refreshed daily; "
			+ "needs Timedata. 0: the fixed efficiency below is used.")
	int efficiencyDays() default 30;

	@AttributeDefinition(name = "Efficiency [%]", description = "Round-trip efficiency until it is measured, or "
			+ "always with period 0.")
	int efficiency() default 90;

	@AttributeDefinition(name = "History [days]", description = "On start the content and its price are rebuilt from "
			+ "this many days of Timedata history. 0: the content starts without price until the first charge.")
	int historyDays() default 14;

	@AttributeDefinition(name = "Debug Mode", description = "Logs the inventory every cycle.")
	boolean debugMode() default false;

	@AttributeDefinition(name = "Ess target filter", description = "This is auto-generated by 'Ess-ID'.")
	String ess_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Ess Energy Price [{id}]";
}
