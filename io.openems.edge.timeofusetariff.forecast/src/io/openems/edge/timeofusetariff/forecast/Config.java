package io.openems.edge.timeofusetariff.forecast;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Time-Of-Use Tariff Forecast", //
		description = "Electricity price outlook for the next days: the published prices of the Time-of-Use tariff, "
				+ "continued with a day-ahead price forecast (EpexPredictor, free, fair use). For display only; "
				+ "neither the optimizer nor any controller reads it.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "priceForecast0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Time-of-Use Tariff-ID", description = "ID of the Time-of-Use tariff. Its published "
			+ "prices (today and, once known, tomorrow) come first; the forecast only continues them.")
	String timeOfUseTariff_id() default "timeOfUseTariff0";

	@AttributeDefinition(name = "Forecast URL", description = "EpexPredictor endpoint. The query parameters region, "
			+ "surcharge, taxPercent, unit and hours are appended.")
	String url() default "https://epexpredictor.batzill.com/prices_short";

	@AttributeDefinition(name = "Region", description = "Bidding zone, e.g. DE, AT, FR, NL.")
	String region() default "DE";

	@AttributeDefinition(name = "Surcharge [Cent/kWh]", description = "Net surcharge on the exchange price: grid fees, "
			+ "levies and electricity tax, without VAT. Choose it so that the forecast matches the tariff where both "
			+ "overlap; the debug log shows the difference.")
	double surchargeCt() default 17.4;

	@AttributeDefinition(name = "VAT [%]", description = "VAT applied to exchange price plus surcharge.")
	int taxPercent() default 19;

	@AttributeDefinition(name = "Horizon [h]", description = "Hours of forecast requested from now; the service "
			+ "delivers about five days.")
	int horizonHours() default 144;

	@AttributeDefinition(name = "Window [h]", description = "Length of the cheapest charging window shown per day.")
	int windowHours() default 4;

	@AttributeDefinition(name = "Rating: 2 Euro from [Cent/kWh]", description = "Prices below this count as cheap "
			+ "(1 Euro sign).")
	int ratingLevel2() default 40;

	@AttributeDefinition(name = "Rating: 3 Euro from [Cent/kWh]", description = "")
	int ratingLevel3() default 45;

	@AttributeDefinition(name = "Rating: 4 Euro from [Cent/kWh]", description = "")
	int ratingLevel4() default 50;

	@AttributeDefinition(name = "Rating: 5 Euro from [Cent/kWh]", description = "Prices from this on count as "
			+ "expensive (5 Euro signs).")
	int ratingLevel5() default 55;

	@AttributeDefinition(name = "Debug Mode", description = "Logs the outlook and the tariff/forecast difference "
			+ "every cycle.")
	boolean debugMode() default false;

	@AttributeDefinition(name = "Time-of-Use Tariff target filter", description = "This is auto-generated by "
			+ "'Time-of-Use Tariff-ID'.")
	String timeOfUseTariff_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Time-Of-Use Tariff Forecast [{id}]";
}
